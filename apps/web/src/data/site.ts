import { z } from '../config/schema-runtime';
import data from './site.json';
import { publicPageKeys, editorialPageKeys } from '../protocol';
const text = z.string().min(1);
const copyKeys = [
  'invalidForm',
  'getStarted',
  'workspace',
  'how',
  'explore',
  'contact',
  'menu',
  'close',
  'pause',
  'play',
  'home',
  'read',
  'back',
  'all',
  'next',
  'edit',
  'review',
  'name',
  'email',
  'company',
  'industry',
  'message',
  'team',
  'request',
  'reviewHeading',
  'reviewText',
  'reviewAction',
  'privacy',
  'footerNote',
  'copyright',
  'pageNav',
  'faq',
  'learn',
  'planAction',
  'integrationAction',
  'selected',
  'conversation',
  'booking',
  'caller',
  'voice',
  'callText',
  'callTime',
  'activity',
  'storyEyebrow',
  'storyTitle',
  'storyText',
  'sectionFeatures',
  'featureHeading',
  'industryEyebrow',
  'industryHeading',
  'integrationsEyebrow',
  'integrationsHeading',
  'integrationsText',
  'faqHeading',
  'ctaEyebrow',
  'ctaHeading',
  'ctaText',
  'businessStrip',
  'introProductEyebrow',
  'introProductTitle',
  'introProductText',
  'onboardingEyebrow',
  'onboardingHeading',
  'onboardingText',
  'contactEyebrow',
  'contactHeading',
  'contactText',
  'detailsStep',
  'preferencesStep',
  'readyStep',
  'voiceLabel',
] as const;
const feature = z.object({ id: text, icon: text, title: text, text, detail: text });
const page = z.object({ eyebrow: text, title: text, text });
export const siteSchema = z.object({
  nav: z.array(z.object({ id: z.enum(publicPageKeys), label: text })).min(1),
  labels: z.record(z.enum(copyKeys), text),
  teamChoices: z.array(text).min(1),
  hero: z.object({
    eyebrow: text,
    lines: z.array(text).min(2),
    description: text,
    points: z.array(text).min(1),
    scroll: text,
  }),
  workflow: z
    .array(
      z.object({
        title: text,
        description: text,
        label: text,
        icon: text,
        detail: text,
        detailText: text,
      }),
    )
    .length(3),
  features: z.array(feature).min(1),
  industries: z
    .array(
      z.object({
        id: text,
        label: text,
        icon: text,
        headline: text,
        text,
        items: z.array(text).min(1),
        tag: text,
        quote: text,
        reply: text,
      }),
    )
    .min(1),
  integrations: z.array(text).min(1),
  faq: z.array(z.object({ question: text, answer: text })).min(1),
  pages: z.record(z.enum(editorialPageKeys), page),
  plans: z
    .array(
      z.object({
        name: text,
        eyebrow: text,
        description: text,
        price: text,
        priceNote: text,
        featured: z.boolean(),
        features: z.array(text).min(1),
      }),
    )
    .length(3),
  comparison: z.array(z.object({ label: text, values: z.array(text).length(3) })).min(1),
  values: z.array(z.object({ number: text, title: text, text })).min(1),
  companyStory: z.object({ eyebrow: text, title: text, paragraphs: z.array(text).min(1) }),
  resources: z
    .array(
      z.object({
        id: text,
        category: text,
        title: text,
        summary: text,
        minutes: text,
        paragraphs: z.array(text).min(1),
      }),
    )
    .min(1),
  visual: z.object({
    cameraNear: z.number().positive(),
    cameraFar: z.number().positive(),
    maxFrameDeltaMs: z.number().int().positive(),
    cameraFov: z.number().min(10).max(90),
    ambientIntensity: z.number().positive(),
    clearcoat: z.number().min(0).max(1),
    clearcoatRoughness: z.number().min(0).max(1),
    iridescence: z.number().min(0).max(1),
    iridescenceIOR: z.number().positive(),
    environmentIntensity: z.number().positive(),
    initialRotation: z.tuple([z.number(), z.number(), z.number()]),
    torusRadius: z.number().positive(),
    tubeRadius: z.number().positive(),
    tubularSegments: z.number().int().min(16).max(256),
    radialSegments: z.number().int().min(8).max(64),
    knotP: z.number().int().positive(),
    knotQ: z.number().int().positive(),
    cameraDistance: z.number().positive(),
    rotationSpeed: z.number().min(0).max(0.01),
    maxPixelRatio: z.number().min(1).max(2),
    exposure: z.number().positive(),
    metalness: z.number().min(0).max(1),
    roughness: z.number().min(0).max(1),
    colors: z.array(text.regex(/^#[a-f0-9]{6}$/i)).length(3),
    lightIntensity: z.number().positive(),
    pointerTilt: z.number().min(0).max(1),
  }),
  motion: z.object({
    floatDistance: z.number().min(0).max(50),
    revealDistance: z.number().min(0).max(100),
    revealSeconds: z.number().positive().max(2),
    staggerSeconds: z.number().min(0).max(1),
    floatSeconds: z.number().positive(),
    orbitSeconds: z.number().positive(),
    springStiffness: z.number().positive(),
    springDamping: z.number().positive(),
    viewportAmount: z.number().min(0).max(1),
    heroParallax: z.number().min(0).max(200),
    visualScaleStart: z.number().positive(),
    visualScaleEnd: z.number().positive(),
    storyParallax: z.number().min(0).max(200),
  }),
});
export function validateSite(value: unknown) {
  const parsed = siteSchema.parse(value);
  for (const collection of [parsed.nav, parsed.features, parsed.industries, parsed.resources]) {
    if (new Set(collection.map((item) => item.id)).size !== collection.length)
      throw new Error('Duplicate public content identity');
  }
  return parsed;
}
export const site = validateSite(data);
